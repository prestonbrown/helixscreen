#
# What each trampolined GPU-library function returns, so the stand-in for a
# missing library can answer with a failure the caller recognises.
#
# mk/implib.mk runs this against the generated <lib>.init.c tables (the
# functions) and the libraries' own headers in the toolchain sysroot (their
# return types), and compiles the C table it writes into the binary.
# helix_gpu_lib_symbol() (src/platform/display/gpu_libs.cpp) looks each function up there.
#
# Kinds:
#   i  -1 with errno = ENOSYS: a signed integer from libdrm or libinput, where
#      0 means success, and every *_get_fd* function, where 0 is stdin
#   d  0.0: a double or float, which comes back in a floating-point register
#   z  0: a pointer (NULL), EGLBoolean (EGL_FALSE), an EGL handle (EGL_NO_*),
#      an unsigned or enum value, void, and anything the headers do not declare
#
# Usage:
#   scripts/gpu_lib_return_kinds.py --out returns.c --init-c a.init.c ... --header h.h ...

from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

SYM_RE = re.compile(r'^\s*"([A-Za-z_][A-Za-z0-9_]*)",\s*$')
SIGNED_INTS = {"int", "int32_t", "int64_t", "long", "ssize_t", "off_t"}
NEGATIVE_FAILURE_PREFIXES = ("drm", "libinput_")


def function_names(init_c: Path) -> list[str]:
    return [m.group(1) for line in init_c.read_text().splitlines() if (m := SYM_RE.match(line))]


def declarations(headers: list[Path]) -> str:
    text = "\n".join(h.read_text(errors="replace") for h in headers)
    text = re.sub(r"/\*.*?\*/", " ", text, flags=re.S)
    text = re.sub(r"//[^\n]*", " ", text)
    text = re.sub(r"^\s*#[^\n]*(\\\n[^\n]*)*", " ", text, flags=re.M)
    return re.sub(r"\s+", " ", text)


def return_prefix(decls: str, name: str) -> str | None:
    """The tokens before NAME( in its declaration, or None when undeclared."""
    m = re.search(r"(?:^|[;{}])\s*([^;{}()]*?)\b" + re.escape(name) + r"\s*\(", decls)
    return m.group(1) if m else None


def kind_of(name: str, prefix: str | None) -> str:
    if prefix is None or "*" in prefix:
        return "z"
    words = set(prefix.split())
    if words & {"double", "float"}:
        return "d"
    if "_get_fd" in name:
        return "i"
    if name.startswith(NEGATIVE_FAILURE_PREFIXES) and words & SIGNED_INTS and "unsigned" not in words:
        return "i"
    return "z"


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--out", required=True, type=Path)
    ap.add_argument("--init-c", nargs="+", required=True, type=Path)
    ap.add_argument("--header", nargs="+", required=True, type=Path)
    args = ap.parse_args()

    names = sorted({n for f in args.init_c for n in function_names(f)})
    if not names:
        print("gpu_lib_return_kinds: no functions in the trampoline tables", file=sys.stderr)
        return 1
    decls = declarations(args.header)
    rows = [(n, kind_of(n, return_prefix(decls, n))) for n in names]

    lines = [
        "/* Generated by scripts/gpu_lib_return_kinds.py. Do not edit. */",
        "#include <stddef.h>",
        "struct HelixGpuReturnKind { const char* name; char kind; };",
        "const struct HelixGpuReturnKind helix_gpu_lib_return_kinds[] = {",
        *[f'    {{"{n}", \'{k}\'}},' for n, k in rows],
        "};",
        f"const size_t helix_gpu_lib_return_kind_count = {len(rows)};",
        "",
    ]
    args.out.write_text("\n".join(lines))
    return 0


if __name__ == "__main__":
    sys.exit(main())
