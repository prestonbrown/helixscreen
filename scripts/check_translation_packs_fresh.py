"""Gate: the committed translation packs are what translations/*.yml generates.

ui_xml/translations/*.xml are generated by `make translations` from translations/*.yml.
A merge keeps one side's packs (merge=helix-generated in .gitattributes), and a rebase,
cherry-pick or hand edit can leave them behind the YAML the same way. A stale pack ships
strings the catalog no longer has, or lacks ones it gained, and nothing at runtime says so.

This regenerates the packs into a scratch directory from the YAML and generator in the
INDEX (git checkout-index), never the working tree, so a session's uncommitted edits can
neither fail nor pass it, and compares them with the packs in the index. In a clean tree,
and in pre-push's checkout of the pushed commit, the index is the commit. About 2 s.

Runs as qc_translation_packs_fresh (commit, push, make land-gate, CI) and from
.githooks/pre-merge-commit, which stops a clean merge that left the packs stale.

Exit 1 when a pack differs, is missing or is extra; 0 otherwise, and 0 with a note when the
generator's python (.venv, else this one) has no yaml.
"""

from __future__ import annotations

import subprocess
import sys
import tempfile
from pathlib import Path

PACKS = "ui_xml/translations"
INPUTS = ("translations", "scripts/generate_translations.py", "scripts/translations")
FIX = "make translations && git add ui_xml/translations && git commit"


def git(*args: str, data: bytes | None = None) -> bytes:
    return subprocess.run(["git", *args], input=data, check=True, capture_output=True).stdout


def generator_python(root: Path) -> str:
    venv = root / ".venv/bin/python3"
    return str(venv) if venv.exists() else sys.executable


def main() -> int:
    root = Path(git("rev-parse", "--show-toplevel").decode().strip())
    py = generator_python(root)
    with tempfile.TemporaryDirectory(prefix="packs-fresh-") as tmp:
        src, out = Path(tmp, "src"), Path(tmp, "out")
        listed = git("-C", str(root), "ls-files", "-z", "--", *INPUTS)
        git("-C", str(root), "checkout-index", "-z", "--stdin", f"--prefix={src}/", data=listed)
        out.mkdir()
        run = subprocess.run([py, str(src / "scripts/generate_translations.py"),
                              "--yaml-dir", str(src / "translations"), "--xml-dir", str(out)],
                             capture_output=True, text=True)
        if "No module named 'yaml'" in run.stderr:
            print("ℹ️  Translation packs: no python with yaml to run the generator; not checked "
                  "(make venv-setup)")
            return 0
        if run.returncode != 0:
            print(f"❌ Translation packs: the generator failed on the staged YAML:\n"
                  f"{run.stdout}{run.stderr}")
            return 1
        made = {p.name: p for p in out.glob("*.xml")}
        committed = {}
        for row in git("-C", str(root), "ls-files", "-s", "--", f"{PACKS}/*.xml").decode().splitlines():
            meta, path = row.split("\t", 1)
            committed[Path(path).name] = meta.split()[1]
        stale = []
        for name, path in sorted(made.items()):
            blob = git("hash-object", str(path)).decode().strip()
            if committed.get(name) != blob:
                stale.append(f"{name} ({'differs' if name in committed else 'missing'})")
        stale += [f"{name} (no locale generates it)" for name in sorted(set(committed) - set(made))]
    if stale:
        print(f"❌ Translation packs: {PACKS}/ does not match translations/*.yml: "
              f"{', '.join(stale)}")
        print(f"   Fix: {FIX}")
        return 1
    print(f"✅ Translation packs: {len(made)} match translations/*.yml")
    return 0


if __name__ == "__main__":
    sys.exit(main())
