"""Regenerate docs/devel/GALLERY.md from docs/images/doc-screenshots.yml.

Lists every `app` image in the manifest, grouped by area. The area comes from
the file name: docs/images/screenshot-*.png are the main panels; for
docs/images/user/<area>-<name>.png the first dash-separated word names the area
(a name with no dash is its own area's overview shot).

    gen_gallery.py            write docs/devel/GALLERY.md
    gen_gallery.py --check    exit 1 if the file differs from what would be written
"""

from __future__ import annotations

import argparse
import posixpath
import sys
from pathlib import Path

try:
    import yaml
except ImportError:
    raise SystemExit("gen_gallery.py needs PyYAML: run it with .venv/bin/python3 "
                     "(make venv-setup), or pip install -r requirements.txt")

REPO_ROOT = Path(__file__).resolve().parents[1]
MANIFEST = REPO_ROOT / "docs" / "images" / "doc-screenshots.yml"
GALLERY = REPO_ROOT / "docs" / "devel" / "GALLERY.md"
GALLERY_DIR = "docs/devel"

MAIN_PANELS = "Main panels"
AREA_TITLES = {
    "advanced": "Advanced",
    "ams": "Filament (AMS)",
    "color": "Filament (AMS)",
    "runout": "Filament (AMS)",
    "controls": "Controls",
    "home": "Home",
    "preflight": "Printing",
    "print": "Printing",
    "screen": "Lock screen",
    "settings": "Settings",
}
AREA_ORDER = [MAIN_PANELS, "Home", "Controls", "Printing", "Filament (AMS)",
              "Advanced", "Settings", "Lock screen"]


def area_of(path: str) -> str:
    stem = posixpath.basename(path).rsplit(".", 1)[0]
    if not path.startswith("docs/images/user/"):
        return MAIN_PANELS
    return AREA_TITLES.get(stem.split("-")[0], stem.split("-")[0].capitalize())


def caption_of(path: str) -> str:
    stem = posixpath.basename(path).rsplit(".", 1)[0]
    if stem.startswith("screenshot-"):
        stem = stem[len("screenshot-"):]
    return stem.replace("-", " ").capitalize()


def render(entries: list[dict]) -> str:
    groups: dict[str, list[str]] = {}
    for e in entries:
        if e.get("kind") == "app":
            groups.setdefault(area_of(e["path"]), []).append(e["path"])
    order = [a for a in AREA_ORDER if a in groups] + sorted(a for a in groups if a not in AREA_ORDER)
    out = ["# Screenshot Gallery", "",
           "Every app screenshot the docs show, grouped by area. Generated by "
           "`scripts/gen_gallery.py` from `docs/images/doc-screenshots.yml`; "
           "recapture the images with `make doc-screenshots`.", ""]
    for area in order:
        out += ["## " + area, ""]
        for path in sorted(groups[area]):
            rel = posixpath.relpath(path, GALLERY_DIR)
            cap = caption_of(path)
            out += [f"### {cap}", "", f'<img src="{rel}" alt="{cap}" width="400"/>', ""]
    return "\n".join(out).rstrip("\n") + "\n"


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("--check", action="store_true")
    ap.add_argument("--manifest", type=Path, default=MANIFEST)
    ap.add_argument("--out", type=Path, default=GALLERY)
    args = ap.parse_args(argv)
    entries = yaml.safe_load(args.manifest.read_text())["images"]
    text = render(entries)
    if args.check:
        if not args.out.exists() or args.out.read_text() != text:
            print(f"{args.out}: stale, run scripts/gen_gallery.py", file=sys.stderr)
            return 1
        return 0
    args.out.write_text(text)
    return 0


if __name__ == "__main__":
    sys.exit(main())
