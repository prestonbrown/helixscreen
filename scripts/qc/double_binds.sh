# ====================================================================
# Generated double-bind inventory ([bind_compose])
# ====================================================================
# tests/unit/double_bind_widgets.inc is the table of ui_xml widgets carrying
# two or more bindings on one property, generated by
# scripts/scan_double_binds.py. The test can only drive the rows it was given,
# so a stale table drops coverage without failing anything. ~0.2s.
qc_double_binds() {
  local EXIT_CODE=0
  local mode=""
  [ "$STAGED_ONLY" = true ] && mode="--staged-only"
  # shellcheck disable=SC2086
  if python3 scripts/scan_double_binds.py --check $mode >"$QC_TMP/double_binds.out" 2>&1; then
    qc_count "$(cat "$QC_TMP/double_binds.out")"
  else
    cat "$QC_TMP/double_binds.out"
    EXIT_CODE=1
  fi
  echo ""
  return $EXIT_CODE
}

QC_TRIGGER_qc_double_binds='^ui_xml/.*\.xml$|^tests/unit/double_bind_widgets\.inc$|^scripts/(scan_double_binds|staged_content)\.py$'
