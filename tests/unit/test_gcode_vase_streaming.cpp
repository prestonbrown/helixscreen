class TempGCodeFile {
  public:
    TempGCodeFile(const std::string& tag, const std::string& content) {
        path_ = "/tmp/test_vase_1127_" + tag + "_" + std::to_string(::getpid()) + ".gcode";
        std::ofstream f(path_);
        f << content;
    }
    ~TempGCodeFile() {
        std::remove(path_.c_str());
    }
    const std::string& path() const {
        return path_;
    }

  private:
    std::string path_;
};

// Orca-style prologue. M83 is the load-bearing line: it is emitted exactly once,
// before every layer's byte range.
const char* PROLOGUE = R"(; generated by test
M190 S60
M104 S210
G90
M83 ; use relative distances for extrusion
G28
G1 Z0.2 F1000
;TYPE:Custom
G1 X2 Y2 Z0.2 E5.0 F1200
)";

// Square ring of `side` mm centred on (110,110), emitted as `steps` equal moves.
// Equal-length moves mean an identical E value on every line — exactly what a
// spiral emits, and the input that collapsed to a zero delta.
void emit_ring(std::string& out, float z_start, float z_step_per_move, float half, int steps,
               bool z_on_every_move) {
    const float cx = 110.0f, cy = 110.0f;
    char buf[160];
    float z = z_start;
    for (int i = 0; i < steps; ++i) {
        // Walk the perimeter of the square.
        float t = 4.0f * static_cast<float>(i) / static_cast<float>(steps);
        float x, y;
        if (t < 1.0f) {
            x = cx - half + 2 * half * t;
            y = cy - half;
        } else if (t < 2.0f) {
            x = cx + half;
            y = cy - half + 2 * half * (t - 1.0f);
        } else if (t < 3.0f) {
            x = cx + half - 2 * half * (t - 2.0f);
            y = cy + half;
        } else {
            x = cx - half;
            y = cy + half - 2 * half * (t - 3.0f);
        }
        z += z_step_per_move;
        if (z_on_every_move) {
            // Leading-dot E, constant per move — the Orca spiral-vase form.
            snprintf(buf, sizeof(buf), "G1 Z%.3f X%.3f Y%.3f E.07628\n", z, x, y);
        } else {
            snprintf(buf, sizeof(buf), "G1 X%.3f Y%.3f E.07628\n", x, y);
        }
        out += buf;
    }
}

std::string make_vase_gcode(int layers, int steps_per_layer) {
    std::string g = PROLOGUE;
    const float layer_h = 0.2f;
    float z = 0.2f;
    for (int l = 0; l < layers; ++l) {
        g += ";LAYER_CHANGE\n";
        char buf[64];
        snprintf(buf, sizeof(buf), ";Z:%.3f\n", z + layer_h);
        g += buf;
        if (l == 0) {
            g += ";TYPE:Outer wall\n";
        }
        // Z rises continuously across the layer — the defining property of vase mode.
        emit_ring(g, z, layer_h / static_cast<float>(steps_per_layer), 24.5f, steps_per_layer,
                  true);
        z += layer_h;
    }
    return g;
}

// Same geometry and same relative-E convention, but discrete layers: Z only
// changes at the layer boundary. This is the control — it must stay correct.
std::string make_normal_gcode(int layers, int steps_per_layer) {
    std::string g = PROLOGUE;
    const float layer_h = 0.2f;
    float z = 0.2f;
    for (int l = 0; l < layers; ++l) {
        z += layer_h;
        g += ";LAYER_CHANGE\n";
        char buf[64];
        snprintf(buf, sizeof(buf), ";Z:%.3f\n", z);
        g += buf;
        snprintf(buf, sizeof(buf), "G1 Z%.3f F24000\n", z);
        g += buf;
        if (l == 0) {
            g += ";TYPE:Outer wall\n";
        }
        emit_ring(g, z, 0.0f, 24.5f, steps_per_layer, false);
    }
    return g;
}

// Count extrusion segments the streaming path produces for one layer.
struct LayerProbe {
    size_t total = 0;
    size_t extrusion = 0;
};

LayerProbe probe_layer(GCodeStreamingController& ctl, size_t layer) {
    LayerProbe p;
    auto segs = ctl.get_layer_segments(layer);
    if (!segs) {
        return p;
    }
    p.total = segs->size();
    for (const auto& s : *segs) {
        if (s.is_extrusion) {
            p.extrusion++;
        }
    }
    return p;
}

