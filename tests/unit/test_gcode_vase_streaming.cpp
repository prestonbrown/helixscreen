// Regression tests for prestonbrown/helixscreen#1127.
//
// Streaming mode re-parses each layer's byte range with a fresh GCodeParser.
// M82/M83 sit once in the file prologue, outside every layer range, so the
// fresh parser assumed absolute E and read relative deltas as absolute
// positions — its computed delta was then the difference *between consecutive
// deltas*. Spiral-vase G-code repeats one E value for the entire spiral, making
// that difference exactly zero and classifying the whole model as travel.
//
// The fixtures below are generated rather than checked in: they reproduce the
// exact shape of OrcaSlicer output (M83 prologue, ;LAYER_CHANGE markers, Z on
// every move, leading-dot E values) at a few KB instead of hundreds.

