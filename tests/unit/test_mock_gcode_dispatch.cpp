struct DispatchCase {
    PT type;
    const char* ams;  ///< HELIX_MOCK_AMS (nullptr = unset)
    const char* objs; ///< HELIX_MOCK_OBJECTS (nullptr = unset)
    bool sync;        ///< true: notifications are dispatched on the calling thread
    std::vector<std::string> scripts;
    const char* expected;
};

// Mesh heights are randomised per calibration; only their shape is pinned.
std::string mesh_shape(const json& matrix) {
    if (!matrix.is_array() || matrix.empty()) {
        return "0x0";
    }
    return std::to_string(matrix.size()) + "x" + std::to_string(matrix[0].size());
}

std::string frame_text(json n) {
    if (n.contains("params") && n["params"].is_array() && !n["params"].empty() &&
        n["params"][0].is_object() && n["params"][0].contains("bed_mesh")) {
        json& mesh = n["params"][0]["bed_mesh"];
        if (mesh.contains("probed_matrix")) {
            mesh["probed_matrix"] = mesh_shape(mesh["probed_matrix"]);
        }
        if (mesh.contains("profiles")) {
            for (auto& [name, profile] : mesh["profiles"].items()) {
                profile["points"] = mesh_shape(profile["points"]);
            }
        }
    }
    return n.dump();
}

std::string snapshot(const DispatchCase& c) {
    ScopedEnv ams_env("HELIX_MOCK_AMS", c.ams);
    ScopedEnv objs_env("HELIX_MOCK_OBJECTS", c.objs);

    MoonrakerClientMock mock(c.type);
    std::vector<std::string> frames;
    mock.register_notify_update([&frames](const json& n) { frames.push_back(frame_text(n)); });
    mock.register_method_callback("notify_gcode_response", "pin",
                                  [&frames](const json& n) { frames.push_back(frame_text(n)); });

    std::ostringstream out;
    for (const auto& script : c.scripts) {
        frames.clear();
        const int rc = mock.gcode_script(script);
        out << script << " => rc=" << rc << " err=[" << mock.get_last_gcode_error() << "]";
        if (c.sync) {
            for (const auto& f : frames) {
                out << " {" << f << "}";
            }
        }
        out << " ;; ";
    }
    out << "klippy=" << static_cast<int>(mock.get_klippy_state())
        << " phase=" << static_cast<int>(mock.get_print_phase()) << " excluded=";
    for (const auto& name : mock.get_excluded_objects()) {
        out << name << ",";
    }
    out << " mesh=" << mock.get_active_bed_mesh().name << " profiles=";
    for (const auto& p : mock.get_bed_mesh_profiles()) {
        out << p << ",";
    }
    out << " tool=" << mock.get_active_gcode_tool();
    return out.str();
}

