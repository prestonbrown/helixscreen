/**
 * @file test_mock_gcode_dispatch.cpp
 * @brief Pins MoonrakerClientMock::gcode_script's observable behaviour per command
 *
 * Every row runs a script sequence on a fresh mock and compares one line of
 * snapshot (return code, error latch, every notification dispatched, and the
 * state getters) against the recorded text. Rows cover each recognised command,
 * near-misses that must NOT match, and inputs where two matchers fire on the
 * same line: substring matching means one command can shadow, or run alongside,
 * another, and that ordering is part of the contract.
 *
 * Commands whose effects land on the simulation thread or an lv_timer
 * (restarts, print control, calibration timers, vendor feeder state machines)
 * pin the synchronous half only: return code, error latch and state getters.
 */

