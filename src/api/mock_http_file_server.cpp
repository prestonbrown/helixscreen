/// Real PNG bytes rather than a synthesised image: the decoder under test is
/// stb_image, and the thing worth exercising is production-shaped input
/// (interlacing, palette, alpha), not the smallest buffer that parses.
const char* THUMBNAIL_ASSET = "assets/images/benchy_thumbnail_white.png";

std::vector<uint8_t> read_asset(const std::string& relative) {
    // CWD-relative, the same convention the rest of the tree uses for assets
    // (lv_image_set_src("A:assets/...")). --test is always launched from a
    // tree that has them.
    std::ifstream f(relative, std::ios::binary);
    if (!f) {
        return {};
    }
    return std::vector<uint8_t>((std::istreambuf_iterator<char>(f)),
                                std::istreambuf_iterator<char>());
}

/// Wrap PNG bytes in the slicer thumbnail block gcode_parser.cpp parses:
///   "; thumbnail begin WxH SIZE" / "; <base64>" ... / "; thumbnail end"
std::string make_gcode_header(const std::vector<uint8_t>& png) {
    std::string b64 = hv::Base64Encode(png.data(), static_cast<unsigned int>(png.size()));

    std::string out;
    out.reserve(b64.size() + 512);
    out += "; generated by HelixScreen MockHttpFileServer\n";
    out += "; thumbnail begin 300x300 " + std::to_string(png.size()) + "\n";
    // Slicers hard-wrap the base64 payload; match that so the extractor's
    // line-oriented accumulation is exercised rather than bypassed.
    constexpr size_t WRAP = 78;
    for (size_t i = 0; i < b64.size(); i += WRAP) {
        out += "; " + b64.substr(i, WRAP) + "\n";
    }
    out += "; thumbnail end\n";
    out += ";FLAVOR:Marlin\n;Generated with MockHttpFileServer\nG28\n";
    return out;
}

/// HELIX_MOCK_RANGE_IGNORE=1 — drop the Range header from every request so
/// libhv answers 200 with the whole body instead of slicing a 206: the
/// behaviour of server forks that never implemented byte ranges.
static bool range_ignore_enabled() {
    static const bool enabled = [] {
        const char* v = std::getenv("HELIX_MOCK_RANGE_IGNORE");
        return v && v[0] && std::string(v) != "0";
    }();
    return enabled;
}

/// Slice a body per a "bytes=a-b" / "bytes=-n" Range header and mark the
/// response 206, the way a range-supporting Moonraker answers. libhv does not
/// do this for a handler-set body, so the server must honour the header
/// itself; HELIX_MOCK_RANGE_IGNORE skips this to emulate a server that never
/// implemented ranges (200, whole file).
void apply_range(HttpRequest* req, HttpResponse* resp) {
    std::string range = req->GetHeader("Range");
    if (range.rfind("bytes=", 0) != 0 || resp->body.empty()) {
        return;
    }
    size_t dash = range.find('-', 6);
    if (dash == std::string::npos) {
        return;
    }
    size_t start = 0;
    size_t end = 0;
    if (dash == 6) { // suffix form: the last N bytes
        size_t n = static_cast<size_t>(atoi(range.c_str() + 7));
        n = std::min(n, resp->body.size());
        start = resp->body.size() - n;
        end = resp->body.size() - 1;
    } else {
        start = static_cast<size_t>(atoi(range.c_str() + 6));
        end = range.size() > dash + 1 ? static_cast<size_t>(atoi(range.c_str() + dash + 1))
                                      : resp->body.size() - 1;
        end = std::min(end, resp->body.size() - 1);
        if (start > end) {
            return;
        }
    }
    resp->status_code = HTTP_STATUS_PARTIAL_CONTENT;
    resp->SetHeader("Content-Range", "bytes " + std::to_string(start) + "-" + std::to_string(end) +
                                         "/" + std::to_string(resp->body.size()));
    resp->body = resp->body.substr(start, end - start + 1);
}

bool ends_with(const std::string& s, const std::string& suffix) {
    return s.size() >= suffix.size() &&
           s.compare(s.size() - suffix.size(), suffix.size(), suffix) == 0;
}

/// Bind a loopback listener on an ephemeral port and report which one.
///
/// libhv's http_server_run() skips binding entirely when `port == 0` (it guards
/// on `port > 0`), so asking it for an ephemeral port yields a server that
/// never listens. It does honour a pre-bound descriptor via setListenFD(), and
/// handing it one is also race-free — picking a port, closing, and re-binding
/// would leave a window for another process to take it.
int bind_loopback_ephemeral(int* out_port) {
    int fd = ::socket(AF_INET, SOCK_STREAM, 0);
    if (fd < 0) {
        return -1;
    }
    int reuse = 1;
    ::setsockopt(fd, SOL_SOCKET, SO_REUSEADDR, &reuse, sizeof(reuse));

    sockaddr_in addr{};
    addr.sin_family = AF_INET;
    addr.sin_addr.s_addr = htonl(INADDR_LOOPBACK);
    addr.sin_port = 0;
    if (::bind(fd, reinterpret_cast<sockaddr*>(&addr), sizeof(addr)) != 0 ||
        ::listen(fd, 16) != 0) {
        ::close(fd);
        return -1;
    }

    sockaddr_in bound{};
    socklen_t len = sizeof(bound);
    if (::getsockname(fd, reinterpret_cast<sockaddr*>(&bound), &len) != 0) {
        ::close(fd);
        return -1;
    }
    *out_port = ntohs(bound.sin_port);
    return fd;
}

